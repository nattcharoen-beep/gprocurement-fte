/**
 * Extract province name from department, title, or raw province string
 * @param {string} deptName 
 * @param {string} title 
 * @param {string} rawProvince 
 * @returns {string} Clean province name (without 'จ.' or 'จังหวัด') or 'ไม่ระบุ'
 */
export function extractProvince(deptName = '', title = '', rawProvince = '') {
  // 1. If valid province already given by e-GP
  if (rawProvince && rawProvince !== 'ไม่ระบุ' && rawProvince !== 'null' && rawProvince.trim() !== '') {
    const clean = rawProvince.replace(/^จ(ังหวัด|\.)\s*/, '').trim();
    if (PROVINCES.includes(clean)) return clean;
  }

  const cleanDept = (deptName || '').trim();
  const cleanTitle = (title || '').trim();
  const combined = `${cleanDept} ${cleanTitle}`;

  // 1.5 Special overrides (campuses, specific hospitals/courts)
  for (const o of SPECIAL_OVERRIDES) {
    if (combined.includes(o.match)) return o.prov;
  }

  // 2. Direct match with "จังหวัด[ชื่อจังหวัด]" or "จ.[ชื่อจังหวัด]" in title or dept
  for (const prov of PROVINCES) {
    const reg1 = new RegExp(`จังหวัด${prov}`);
    const reg2 = new RegExp(`จ\\.${prov}`);
    if (reg1.test(combined) || reg2.test(combined)) {
      return prov;
    }
  }

  // 3. Direct match with exact province name inside deptName
  for (const prov of PROVINCES) {
    if (cleanDept.includes(prov)) {
      return prov;
    }
  }

  // 4. Check district / locality mapping
  for (const [key, prov] of Object.entries(DISTRICT_MAP)) {
    if (cleanDept.includes(key) || cleanTitle.includes(key)) {
      return prov;
    }
  }

  // 5. Direct match with province name anywhere in title
  for (const prov of PROVINCES) {
    if (prov === 'แพร่') {
      if (combined.includes('จ.แพร่') || combined.includes('จังหวัดแพร่') || cleanDept.includes('แพร่')) return 'แพร่';
      continue;
    }
    if (prov === 'เลย') {
      if (combined.includes('จ.เลย') || combined.includes('จังหวัดเลย') || cleanDept.includes('เลย')) return 'เลย';
      continue;
    }
    if (prov === 'ตาก') {
      if (combined.includes('จ.ตาก') || combined.includes('จังหวัดตาก') || cleanDept.includes('ตาก')) return 'ตาก';
      continue;
    }
    if (cleanTitle.includes(prov)) {
      return prov;
    }
  }

  // 6. Common state agencies headquartered in Bangkok
  if (
    cleanDept.includes('กรุงเทพมหานคร') ||
    cleanDept.includes('กรม') ||
    cleanDept.includes('กระทรวง') ||
    cleanDept.includes('สำนักงานศาลยุติธรรม') ||
    cleanDept.includes('การทางพิเศษ') ||
    cleanDept.includes('การประปานครหลวง') ||
    cleanDept.includes('การกีฬาแห่งประเทศไทย')
  ) {
    return 'กรุงเทพมหานคร';
  }

  return 'ไม่ระบุ';
}
